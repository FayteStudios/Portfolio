export function getPageCards(page) {
  const normalizedTitle = page.title
    ?.toLowerCase()
    .replaceAll(" ", "-")
    .replaceAll("/", "-");

  return (
    pageCardsByPageId[page.id] ||
    pageCardsByPageId[normalizedTitle] ||
    []
  );
}
